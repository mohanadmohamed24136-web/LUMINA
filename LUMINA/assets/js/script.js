function updateUI() {
    document.documentElement.lang = currentLang;
    document.documentElement.dir = currentLang === 'ar' ? 'rtl' : 'ltr';
    document.body.classList.remove('dark', 'light', 'rtl', 'ltr');
    document.body.classList.add(currentTheme, currentLang === 'ar' ? 'rtl' : 'ltr');
    
    const t = translations[currentLang];
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (t[key]) {
            if (key.includes('title')) {
                element.innerHTML = t[key];
            } else {
                element.textContent = t[key];
            }
        }
    });

    const searchInput = document.getElementById('main-search');
    if (searchInput) {
        searchInput.placeholder = t.search;
        // Use a single listener logic
        if (!searchInput.dataset.listenerAttached) {
            searchInput.addEventListener('input', (e) => {
                const query = e.target.value;
                renderHomeProducts(query);
            });
            searchInput.dataset.listenerAttached = "true";
        }
    }

    const langText = document.getElementById('lang-text');
    if (langText) langText.textContent = currentLang.toUpperCase();

    const themeIcon = document.getElementById('theme-icon');
    if (themeIcon) {
        if (currentTheme === 'dark') {
            themeIcon.setAttribute('data-lucide', 'sun');
            themeIcon.classList.add('text-primary-gold');
            themeIcon.classList.remove('text-gray-400');
        } else {
            themeIcon.setAttribute('data-lucide', 'moon');
            themeIcon.classList.add('text-gray-400');
            themeIcon.classList.remove('text-primary-gold');
        }
    }
    
    if (window.lucide) lucide.createIcons();
    updateUserArea();
    updateFavBadge();
    updateCartBadge();
}

