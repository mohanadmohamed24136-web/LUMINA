function handleMultipleImages(input) {
    const container = document.getElementById('image-preview-container');
    const status = document.getElementById('upload-status');
    if (!container || !status) return;

    container.innerHTML = '';
    const files = Array.from(input.files).slice(0, 5); // Limit to 5
    
    if (files.length > 0) {
        status.textContent = `${files.length} images selected`;
        files.forEach((file, index) => {
            const reader = new FileReader();
            reader.onload = (e) => {
                const div = document.createElement('div');
                div.className = 'aspect-square rounded-xl overflow-hidden border border-white/10 relative group';
                div.innerHTML = `
                    <img src="${e.target.result}" class="w-full h-full object-cover">
                    <div class="absolute inset-0 bg-black/40 opacity-0 group-hover:opacity-100 transition-opacity flex items-center justify-center">
                        <span class="text-[8px] font-black text-white uppercase">${index === 0 ? 'Primary' : ''}</span>
                    </div>
                `;
                container.appendChild(div);
            };
            reader.readAsDataURL(file);
        });
    } else {
        status.textContent = 'Select up to 5 images';
    }
}

async function initializeAsset() {
    // Ensure app is initialized
    if (!currentUser) {
        const userId = getCookie('userId');
        if (userId) {
            // Wait a bit or try to fetch profile if not yet loaded
            try {
                const response = await fetch(`${API_BASE}/auth/profile?id=${userId}`);
                if (response.ok) {
                    currentUser = await response.json();
                }
            } catch (err) {
                console.error('Wait for user error:', err);
            }
        }
    }

    const user = currentUser;
    if (!user) {
        showToast(currentLang === 'ar' ? 'يجب تسجيل الدخول أولاً' : 'Please login first', 'error');
        return;
    }

    if (!user.phone || !user.address) {
        showToast(currentLang === 'ar' ? 'يجب إكمال بياناتك (الهاتف والعنوان) في لوحة التحكم أولاً' : 'Please complete your profile (Phone and Address) in the dashboard first', 'error');
        if (user.role === 'designer') window.location.href = 'designer-portal.html';
        return;
    }

    const name = document.getElementById('prod-name').value;
    const price = document.getElementById('prod-price').value;
    const imageFiles = document.getElementById('prod-image')?.files;
    const sizeS = document.getElementById('size-s').value;
    const sizeM = document.getElementById('size-m').value;
    const sizeL = document.getElementById('size-l').value;
    const sizeXL = document.getElementById('size-xl').value;
    const sizeXXL = document.getElementById('size-xxl').value;
    const quantity = document.getElementById('prod-quantity').value;
    const colors = document.getElementById('prod-colors').value;
    const description = document.getElementById('prod-description').value;

    // Comprehensive Field Validation
    const requiredFields = [
        { id: 'prod-name', value: name, label: currentLang === 'ar' ? 'اسم المنتج' : 'Product Name' },
        { id: 'prod-price', value: price, label: currentLang === 'ar' ? 'السعر' : 'Price' },
        { id: 'prod-quantity', value: quantity, label: currentLang === 'ar' ? 'الكمية' : 'Quantity' },
        { id: 'size-s', value: sizeS, label: currentLang === 'ar' ? 'مقاس S' : 'Size S' },
        { id: 'size-m', value: sizeM, label: currentLang === 'ar' ? 'مقاس M' : 'Size M' },
        { id: 'size-l', value: sizeL, label: currentLang === 'ar' ? 'مقاس L' : 'Size L' },
        { id: 'size-xl', value: sizeXL, label: currentLang === 'ar' ? 'مقاس XL' : 'Size XL' },
        { id: 'size-xxl', value: sizeXXL, label: currentLang === 'ar' ? 'مقاس XXL' : 'Size XXL' },
        { id: 'prod-description', value: description, label: currentLang === 'ar' ? 'الوصف' : 'Description' }
    ];

    let missingFields = requiredFields.filter(f => !f.value.trim());
    
    if (missingFields.length > 0 || !imageFiles || imageFiles.length === 0) {
        const firstMissing = missingFields.length > 0 ? missingFields[0].label : (currentLang === 'ar' ? 'صورة المنتج' : 'Product Image');
        showToast(currentLang === 'ar' ? `يرجى ملء حقل: ${firstMissing}` : `Please fill the field: ${firstMissing}`, 'error');
        
        // Highlight first missing field
        if (missingFields.length > 0) {
            const el = document.getElementById(missingFields[0].id);
            if (el) {
                el.focus();
                el.classList.add('border-red-500/50');
                setTimeout(() => el.classList.remove('border-red-500/50'), 3000);
            }
        }
        return;
    }

    const formData = new FormData();
    formData.append('name', name.trim());
    formData.append('price', price.toString());
    formData.append('location', (user.address || '').trim());
    formData.append('architect', (user.username || user.name || 'Anonymous').trim());
    formData.append('email', user.email.trim());
    formData.append('phone', (user.phone || '').trim());
    
    // Append multiple images - IMPORTANT: field name must be 'images'
    const files = Array.from(imageFiles).slice(0, 5);
    files.forEach(file => {
        formData.append('images', file);
    });

    formData.append('size_s', (sizeS || '-').trim());
    formData.append('size_m', (sizeM || '-').trim());
    formData.append('size_l', (sizeL || '-').trim());
    formData.append('size_xl', (sizeXL || '-').trim());
    formData.append('size_xxl', (sizeXXL || '-').trim());
    formData.append('quantity', quantity || '1');
    formData.append('colors', (colors || '').trim());
    formData.append('description', (description || '').trim());

    const submitBtn = document.getElementById('initialize-asset-btn');
    const originalBtnContent = submitBtn ? submitBtn.innerHTML : '';
    
    if (submitBtn) {
        submitBtn.disabled = true;
        submitBtn.innerHTML = `
            <div class="flex items-center gap-3">
                <div class="w-4 h-4 border-2 border-black border-t-transparent rounded-full animate-spin"></div>
                <span>Uploading Masterpiece...</span>
            </div>
        `;
    }

    try {
        const controller = new AbortController();
        const timeoutId = setTimeout(() => controller.abort(), 30000); // 30 second timeout

        const response = await fetch(`${API_BASE}/products`, {
            method: 'POST',
            body: formData,
            signal: controller.signal
        });
        clearTimeout(timeoutId);

        const contentType = response.headers.get("content-type");
        let data;
        if (contentType && contentType.indexOf("application/json") !== -1) {
            data = await response.json();
        }

        if (response.ok) {
            currentUser = { ...user, ...data.user };
            showToast(currentLang === 'ar' ? 'تم نشر التصميم بنجاح!' : 'Asset Initialized Successfully!');
            setTimeout(() => location.reload(), 1500);
        } else {
            // Try to get detailed error from response
            let errorMsg = currentLang === 'ar' ? 'حدث خطأ أثناء الرفع' : 'Upload failed';
            if (data && data.error) {
                errorMsg = data.error;
            }
            
            showToast('Error: ' + errorMsg, 'error');
            console.error('Upload Failed:', data);
            
            if (submitBtn) {
                submitBtn.disabled = false;
                submitBtn.innerHTML = originalBtnContent;
            }
        }
    } catch (err) {
        console.error('Upload Error:', err);
        showToast(currentLang === 'ar' ? 'خطأ في الاتصال، يرجى المحاولة لاحقاً' : 'Connection Error, please try again later', 'error');
        if (submitBtn) {
            submitBtn.disabled = false;
            submitBtn.innerHTML = originalBtnContent;
        }
    }
}

