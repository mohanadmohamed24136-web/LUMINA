function authCheck(event, targetUrl) {
    const user = currentUser;
    if (!user) {
        if (event) {
            event.preventDefault();
            event.stopPropagation();
        }
        showToast(currentLang === 'ar' ? 'يجب أن تكون مسجلاً أولاً للقيام بهذا الإجراء' : 'You must be registered first for this action', 'error');
        window.location.href = 'login.html';
        return false;
    }
    if (targetUrl) {
        if (targetUrl.startsWith('#')) {
            const el = document.querySelector(targetUrl);
            if (el) el.scrollIntoView({ behavior: 'smooth' });
        } else {
            window.location.href = targetUrl;
        }
    }
    return true;
}

// --- Profile Management ---
async function triggerPhotoUpload() {
    const input = document.createElement('input');
    input.type = 'file';
    input.accept = 'image/*';
    input.onchange = async (e) => {
        const file = e.target.files[0];
        if (file) {
            const user = currentUser;
            if (!user) return;

            const formData = new FormData();
            formData.append('id', user.id);
            formData.append('photo', file); // This matches backend's upload.single('photo')
            formData.append('username', user.username || user.name);
            formData.append('email', user.email);

            try {
                const response = await fetch(`${API_BASE}/auth/profile`, {
                    method: 'PATCH',
                    body: formData
                });
                if (response.ok) {
                    currentUser = await response.json();
                    location.reload();
                }
            } catch (err) {
                console.error('Photo Upload Error:', err);
            }
        }
    };
    input.click();
}

async function commitChanges() {
    const user = currentUser;
    if (!user) return;

    const name = document.getElementById('input-name').value;
    const phone = document.getElementById('input-phone').value;
    const address = document.getElementById('input-address').value;
    const bio = document.getElementById('input-bio').value;

    const formData = new FormData();
    formData.append('id', user.id);
    formData.append('username', name);
    formData.append('email', user.email);
    formData.append('phone', phone);
    formData.append('address', address);
    formData.append('bio', bio);

    try {
        const response = await fetch(`${API_BASE}/auth/profile`, {
            method: 'PATCH',
            body: formData
        });

        if (response.ok) {
            currentUser = await response.json();
            showToast(currentLang === 'ar' ? 'تم حفظ التغييرات بنجاح' : 'Changes committed successfully');
            setTimeout(() => location.reload(), 1500);
        } else {
            const err = await response.json();
            showToast('Error: ' + err.error, 'error');
        }
    } catch (err) {
        console.error('Update Error:', err);
        showToast('Backend Connection Error!', 'error');
    }
}

