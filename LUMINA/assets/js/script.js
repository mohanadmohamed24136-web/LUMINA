async function toggleFavorite(prodId) {
    if (!currentUser) {
        showToast(currentLang === 'ar' ? 'يجب أن تكون مسجلاً أولاً للقيام بهذا الإجراء' : 'You must be registered first for this action', 'error');
        window.location.href = 'login.html';
        return;
    }

    try {
        const response = await fetch(`${API_BASE}/favorites/toggle`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ user_email: currentUser.email, product_id: prodId })
        });
        
        if (response.ok) {
            currentFavorites = await response.json();
            updateFavBadge();
            
            const isFav = currentFavorites.includes(String(prodId));
            showToast(isFav 
                ? (currentLang === 'ar' ? 'تمت الإضافة للمفضلات' : 'Added to favorites')
                : (currentLang === 'ar' ? 'تمت الإزالة من المفضلات' : 'Removed from favorites')
            );
            
            // Update UI heart icon
            const heartIcon = document.querySelector(`button[onclick="toggleFavorite('${prodId}')"] i`);
            if (heartIcon) {
                if (isFav) {
                    heartIcon.classList.add('fill-primary-magenta', 'text-primary-magenta');
                    heartIcon.classList.remove('text-white');
                } else {
                    heartIcon.classList.remove('fill-primary-magenta', 'text-primary-magenta');
                    heartIcon.classList.add('text-white');
                }
            }
            
            // If modal is open, refresh list
            const favModal = document.getElementById('favorites-modal');
            if (favModal && !favModal.classList.contains('hidden')) {
                renderFavoritesList();
            }
        }
    } catch (err) {
        console.error('Toggle Favorite Error:', err);
    }
}

// --- Toast System ---
function showToast(message, type = 'success') {
    let toastContainer = document.getElementById('toast-container');
    if (!toastContainer) {
        toastContainer = document.createElement('div');
        toastContainer.id = 'toast-container';
        toastContainer.className = 'fixed bottom-8 left-1/2 -translate-x-1/2 z-[200] flex flex-col gap-3 items-center pointer-events-none';
        document.body.appendChild(toastContainer);
    }

    const toast = document.createElement('div');
        toast.className = `glass px-6 py-4 rounded-2xl border ${type === 'error' ? 'border-red-500/30' : 'border-primary-cyan/30'} flex items-center gap-3 animate-slide-up shadow-2xl backdrop-blur-xl pointer-events-auto`;
        
        const icon = type === 'error' ? 'alert-circle' : 'check-circle';
        const iconColor = type === 'error' ? 'text-red-500' : 'text-primary-cyan';

        toast.innerHTML = `
            <i data-lucide="${icon}" class="w-5 h-5 ${iconColor}"></i>
            <span class="text-xs font-black uppercase tracking-widest text-white">${message}</span>
        `;

        toastContainer.appendChild(toast);
        if (window.lucide) lucide.createIcons();

        setTimeout(() => {
            toast.classList.add('animate-fade-out');
            setTimeout(() => toast.remove(), 500);
        }, 3000);
    }

