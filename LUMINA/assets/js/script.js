// Initialize App
async function initApp() {
    // Try to load user from cookie
    const userId = getCookie('userId');
    if (userId) {
        try {
            const response = await fetch(`${API_BASE}/auth/profile?id=${userId}`);
            if (response.ok) {
                currentUser = await response.json();
                // Ensure helper cookies are present
                if (!getCookie('userEmail')) setCookie('userEmail', currentUser.email, 7);
                if (!getCookie('userRole')) setCookie('userRole', currentUser.role, 7);
                
                // Load cart and favorites from DB
                await Promise.all([
                    fetchCart(),
                    fetchFavorites()
                ]);
            } else {
                eraseCookie('userId');
            }
        } catch (err) {
            console.error('Init Auth Error:', err);
        }
    }
    updateUI();
    
    // Page specific initializations
    if (document.getElementById('designer-products-grid')) {
        renderHomeProducts();
        renderAIProducts();
    }
    if (document.getElementById('cart-items-container')) updateCartUI();
    if (window.location.pathname.includes('admin-portal.html')) {
        showAdminTab('overview');
    }

    // Ensure all icons are rendered
    if (window.lucide) lucide.createIcons();
}

